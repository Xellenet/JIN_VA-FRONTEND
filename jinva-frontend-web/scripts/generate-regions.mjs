#!/usr/bin/env node
/**
 * LOC7 (google-signup-prefill): builds `src/lib/regions/{CC}.json` and
 * `src/lib/regions/loaders.ts` from GeoNames' first-level subdivisions.
 *
 * Run: `npm run regions:generate -- <path to admin1CodesASCII.txt> [--retrieved YYYY-MM-DD]`
 *
 * The script NEVER downloads anything. Fetch the file yourself from
 * https://download.geonames.org/export/dump/admin1CodesASCII.txt (CC BY 4.0,
 * credit GeoNames), then point the script at the local copy. Its rows are
 * `CC.code <TAB> name <TAB> asciiname <TAB> geonameid`; the UTF-8 `name` is
 * kept. One file is written per country in `SUPPORTED_PHONE_COUNTRIES` that
 * has rows; the country list is imported from `src/lib/phone.ts` so the two
 * cannot drift.
 *
 * Commit the output. The app loads the files lazily per country and makes no
 * runtime call to GeoNames.
 */
import { readFileSync, writeFileSync } from "node:fs"
import { join } from "node:path"
import { pathToFileURL } from "node:url"

const SOURCE_URL = "https://download.geonames.org/export/dump/admin1CodesASCII.txt"
const LICENCE = "CC BY 4.0 (https://creativecommons.org/licenses/by/4.0/), GeoNames"
const ABOUT =
  "First-level subdivisions for one country, used by the Region field on Complete your account (LOC5, LOC7). " +
  "Data from GeoNames, CC BY 4.0: credit GeoNames (https://www.geonames.org/) on the credits page. " +
  "Regenerate with `node scripts/generate-regions.mjs <path to admin1CodesASCII.txt>`; nothing here is fetched at runtime."

const args = process.argv.slice(2)
const input = args.find((a) => !a.startsWith("--"))
const retrievedFlag = args.indexOf("--retrieved")
const retrieved = retrievedFlag >= 0 ? args[retrievedFlag + 1] : new Date().toISOString().slice(0, 10)

if (!input || !/^\d{4}-\d{2}-\d{2}$/.test(retrieved ?? "")) {
  console.error("Usage: npm run regions:generate -- <path to admin1CodesASCII.txt> [--retrieved YYYY-MM-DD]")
  process.exit(1)
}

const ROOT = process.cwd()
const OUT_DIR = join(ROOT, "src", "lib", "regions")
const { SUPPORTED_PHONE_COUNTRIES } = await import(pathToFileURL(join(ROOT, "src", "lib", "phone.ts")).href)

/** @type {Map<string, string[]>} */
const byCountry = new Map()
for (const line of readFileSync(input, "utf8").split(/\r?\n/)) {
  if (!line.trim()) continue
  const [key, name] = line.split("\t")
  const country = key?.split(".")[0]
  if (!country || !name || !SUPPORTED_PHONE_COUNTRIES.includes(country)) continue
  if (!byCountry.has(country)) byCountry.set(country, [])
  byCountry.get(country).push(name.trim())
}

const written = []
for (const country of SUPPORTED_PHONE_COUNTRIES) {
  const regions = byCountry.get(country)
  if (!regions?.length) {
    console.warn(`${country}: no rows in the input, no file written`)
    continue
  }
  const file = {
    _about: ABOUT,
    source: SOURCE_URL,
    licence: LICENCE,
    retrieved,
    country,
    regions: [...new Set(regions)].sort((a, b) => a.localeCompare(b, "en")),
  }
  writeFileSync(join(OUT_DIR, `${country}.json`), `${JSON.stringify(file, null, 2)}\n`)
  written.push(country)
  console.log(`${country}: ${file.regions.length} regions`)
}

const loaders = written.map(
  (country) => `  ${country}: () => import("./${country}.json").then((m) => m.default as RegionFile),`,
)
writeFileSync(
  join(OUT_DIR, "loaders.ts"),
  [
    "// Generated by scripts/generate-regions.mjs. Do not edit by hand.",
    "//",
    "// One lazy loader per country that has a Region file (LOC7). A country with no",
    "// entry here has no closed Region list yet, and the Region field accepts free",
    "// text for it (see location-field.tsx).",
    'import type { RegionFile } from "./types"',
    "",
    "export const REGION_LOADERS: Partial<Record<string, () => Promise<RegionFile>>> = {",
    ...loaders,
    "}",
    "",
  ].join("\n"),
)
console.log(`Wrote ${written.length} region file(s) and loaders.ts`)
